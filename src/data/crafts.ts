export const getNormalizedTag = (type: 'category' | 'material' | 'technique', value: string) => {
  if (value === "All") return "All";
  if (type === 'category') return categoryMapping[value] || value;
  if (type === 'material') return materialMapping[value] || value;
  if (type === 'technique') return techniqueMapping[value] || value;
  return value;
};

